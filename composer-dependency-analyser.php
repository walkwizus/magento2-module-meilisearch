<?php

declare(strict_types=1);

use ShipMonk\ComposerDependencyAnalyser\Config\Configuration;
use ShipMonk\ComposerDependencyAnalyser\Config\ErrorType;

$config = new Configuration();

return $config
    ->addPathToScan(__DIR__ . '/src', false)
    ->addPathToExclude(__DIR__ . '/src/Test')
    // Libraries shipped with magento/framework, as in Magento core modules.
    ->ignoreErrorsOnPackages(
        [
            'guzzlehttp/guzzle',
            'guzzlehttp/psr7',
            'magento/zend-db',
            'psr/log',
            'symfony/console',
        ],
        [ErrorType::SHADOW_DEPENDENCY]
    )
    // The Meilisearch SDK is installed by the merchant (see README), MSI is used by the inventory attribute mapper.
    ->ignoreErrorsOnPackages(
        [
            'meilisearch/meilisearch-php',
            'magento/module-inventory-catalog-api',
            'magento/module-inventory-indexer',
            'magento/module-inventory-sales-api',
        ],
        [ErrorType::DEV_DEPENDENCY_IN_PROD]
    )
    // Only referenced from XML (ACL resources).
    ->ignoreErrorsOnPackage('magento/module-config', [ErrorType::UNUSED_DEPENDENCY])
    // Factories and proxies are generated by Magento, Magento\Setup is provided by the Magento root package.
    ->ignoreUnknownClassesRegex('~(Factory|\\\\Proxy)$~')
    ->ignoreUnknownClassesRegex('~^Magento\\\\Setup\\\\~');
